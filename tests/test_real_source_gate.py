"""Issue #3: source gate tests use synthetic media ONLY as structural fixtures.

Passing this suite cannot certify that a photographed/model-generated shot
is genuine, visually compelling or human reviewed.
"""
import json
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
from audio_timeline import sha256
from real_source_gate import inspect_media, require_media


class RealSourceGateTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.media = self.root / "media"
        self.media.mkdir()
        self.still = self.media / "test-fixture.png"
        Image.new("RGB", (64, 64), "white").save(self.still)
        self.shot = {
            "id": "v001", "media_type": "screenshot", "roll": "B",
            "visual_event": "Display exact captured evidence",
            "cut_reason": "Let viewer inspect the original evidence",
            "start_ms": 0, "end_ms": 900,
            "source_file": "media/test-fixture.png",
            "source_sha256": sha256(self.still),
            "source_provenance": {
                "origin": "screen_capture", "producer": "unit test fixture",
                "reference": "fixture-not-real-content",
                "source_sha256": sha256(self.still),
                "rights_confirmed": True,
            },
        }

    def inspect(self, *shots):
        return inspect_media(self.root, {"shots": list(shots)})

    def test_empty_and_missing_media_block_with_shot_tasks(self):
        report = inspect_media(self.root, {"shots": []})
        self.assertFalse(report["can_render"])
        shot = dict(self.shot, source_file="media/missing.png")
        report = self.inspect(shot)
        self.assertEqual("BLOCKED_REAL_MEDIA", report["status"])
        self.assertEqual("v001", report["gaps"][0]["shot_id"])
        self.assertIn("Original media file missing", str(report["gaps"]))
        with self.assertRaisesRegex(ValueError, "Authentic-media preflight blocked"):
            require_media(self.root, {"shots": [shot]})

    def test_procedural_video_is_banned_even_with_fake_receipt(self):
        bad = dict(self.shot, media_type="data_motion")
        report = self.inspect(bad)
        self.assertFalse(report["can_render"])
        self.assertIn("procedural", str(report["gaps"]))
        for kind in ("svg", "text_overlay", "original_vector_card"):
            self.assertFalse(self.inspect(dict(self.shot, media_type=kind))["can_render"])

    def test_sha_and_provenance_cannot_be_omitted(self):
        missing = dict(self.shot)
        missing.pop("source_provenance")
        self.assertIn("source_provenance", str(self.inspect(missing)["gaps"]))
        bad = dict(self.shot, source_sha256="0"*64)
        self.assertIn("source SHA256", str(self.inspect(bad)["gaps"]))
        meta = dict(self.shot["source_provenance"], rights_confirmed=False)
        self.assertIn("rights_confirmed", str(self.inspect(dict(self.shot, source_provenance=meta))["gaps"]))
        outside = dict(self.shot, source_file="../outside.png")
        self.assertIn("outside project", str(self.inspect(outside)["gaps"]))

    def test_structural_acceptance_is_not_authenticity_or_creative_approval(self):
        # This bitmap is generated by Pillow as a test fixture; gate checks
        # only the metadata declaration and actual bytes, not creative truth.
        report = self.inspect(self.shot)
        self.assertTrue(report["can_render"])
        self.assertFalse(report["review_approved"])
        self.assertIn("do not prove", report["limitations"][0])

    def test_repeated_static_shot_and_fake_motion_roll_are_blocked(self):
        other = dict(self.shot, id="v002")
        report = self.inspect(self.shot, other)
        self.assertIn("reused", str(report["gaps"]))
        report = self.inspect(dict(self.shot, roll="A"))
        self.assertIn("A-roll", str(report["gaps"]))

    def test_gif_without_registered_generation_is_blocked(self):
        shot = dict(self.shot, media_type="gpt_gif",
                    source_shot_id="shot-01", candidate_id="v1")
        report = self.inspect(shot)
        self.assertIn("registered GIF candidate missing", str(report["gaps"]))

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                         "Real decoded MP4 fixture requires FFmpeg")
    def test_video_declaration_validates_actual_duration(self):
        movie = self.media / "test-video-fixture.mp4"
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                        "-f", "lavfi", "-i", "testsrc=size=160x90:rate=10",
                        "-t", "1", "-pix_fmt", "yuv420p", str(movie)], check=True)
        shot = dict(self.shot,
                    media_type="screen_recording",
                    source_file="media/test-video-fixture.mp4",
                    source_sha256=sha256(movie),
                    source_provenance={
                        "origin": "screen_capture", "producer": "structural fixture",
                        "reference": "synthetic-not-a-real-screen-recording",
                        "source_sha256": sha256(movie), "rights_confirmed": True,
                    })
        # True means the file and declaration are structurally consistent,
        # not that ffprobe can establish how the pixels were produced.
        self.assertTrue(self.inspect(shot)["can_render"])
        self.assertIn("Footage too short", str(self.inspect(dict(shot, end_ms=2500))["gaps"]))


if __name__ == "__main__":
    unittest.main()
